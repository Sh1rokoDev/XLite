        XunleiCodes.AUTH_RES_HAS_NO_QUOTA -> "API 配额不足"
        XunleiCodes.INSUFFICIENT_DISK_SPACE -> "磁盘空间不足"
        XunleiCodes.OPEN_FILE_ERROR -> "无法创建或写入文件，请检查保存目录权限"
