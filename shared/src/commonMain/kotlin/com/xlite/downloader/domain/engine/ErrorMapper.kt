        XunleiCodes.FAILED -> "下载失败，请重试"
        XunleiCodes.ALREADY_INIT -> "下载引擎已初始化"
        XunleiCodes.SDK_NOT_INIT -> "下载引擎尚未初始化"
        XunleiCodes.TASK_ALREADY_EXIST -> "相同链接和保存位置的任务已存在"
        XunleiCodes.TASK_NOT_EXIST -> "任务在下载引擎中不存在"
        XunleiCodes.TASK_ALREADY_STOPPED -> "任务已经暂停"
        XunleiCodes.TASK_ALREADY_RUNNING -> "任务已经在下载"
        XunleiCodes.TASK_NOT_START -> "任务尚未启动"
        XunleiCodes.TASK_STILL_RUNNING -> "任务仍在运行，请先暂停"
        XunleiCodes.FILE_EXISTED -> "目标文件已存在"
        XunleiCodes.DISK_FULL -> "磁盘空间不足"
        XunleiCodes.TOO_MUCH_TASK -> "任务数量过多"
        XunleiCodes.SCHEMA_NOT_SUPPORT -> "仅支持 HTTP/HTTPS 链接"
